import { describe, expect, it } from 'vitest';
import { 创建开局门派状态 } from '../hooks/useGame/storyState';

/**
 * 玩家反馈：「第0回合生成宗门比自己写的优先级更高，会默认直接填充，不顾写的人设」。
 *
 * 根因在创建开局基态这一层：新手向导没有门派名称输入框（`所属门派ID` 恒为 'none'），
 * `生成开局门派名称` 只按固定词池随机取名，并把结果回写进 `角色.所属门派ID`；
 * 建档摘要随后把这个随机组织当作「当前所属门派ID」回喂模型。仅加提示词盯不住，
 * 必须在基态就认出玩家写的门派。
 */

const 武侠词池名 = /^(折柳|玄墨|听潮|照影|归雁|松风|问剑|长鲸)(山庄|门|帮|武馆|剑派|堂)$/;

const 造角色 = (patch: Record<string, any>) => ({
    姓名: '陆行舟',
    所属门派ID: 'none',
    门派职位: '无',
    门派贡献: 0,
    ...patch
} as any);

const 开局配置 = {
    开局生成门派: true,
    开局生成同门: false
} as any;

describe('开局门派名称优先采用建档人设', () => {
    it('出身背景描述里写明的门派会被采用，而不是随机词池名', () => {
        const 门派 = 创建开局门派状态(
            造角色({
                出身背景: {
                    名称: '寒门孤身',
                    描述: '你本是青云剑派的弟子，因故流落江湖。',
                    效果: ''
                }
            }),
            开局配置
        );

        expect(门派.名称).toBe('青云剑派');
        expect(门派.ID).toBe('青云剑派');
        expect(武侠词池名.test(门派.名称)).toBe(false);
    });

    it('开局额外要求里写明的组织同样会被采用', () => {
        const 门派 = 创建开局门派状态(
            造角色({ 出身背景: { 名称: '散人', 描述: '', 效果: '' } }),
            { ...开局配置, 开局额外要求: '主角是听潮阁的弟子，身份是执法堂成员' } as any
        );

        expect(门派.名称).toBe('听潮阁');
    });

    it('天赋描述里写明的组织也会被采用', () => {
        const 门派 = 创建开局门派状态(
            造角色({
                出身背景: { 名称: '寒门孤身', 描述: '', 效果: '' },
                天赋列表: [{ 名称: '宗门遗孤', 描述: '你曾是照影山庄的传人', 效果: '' }]
            }),
            开局配置
        );

        expect(门派.名称).toBe('照影山庄');
    });

    it('泛指描述不会误命中，回退到原有随机词池', () => {
        // 这些写法里没有具体组织名，绝不能抠出「落门派」「拜入门派」之类假名字。
        const 泛指列表 = [
            '你出身于一个没落的门派，早已无依无靠。',
            '少年时拜入门派的弟子众多，你只是最不起眼的一个。',
            '你与同门弟子的关系一向冷淡。',
            '你在各门各派之间游走，谁也不认。'
        ];

        for (const 描述 of 泛指列表) {
            const 门派 = 创建开局门派状态(
                造角色({ 出身背景: { 名称: '寒门孤身', 描述, 效果: '' } }),
                开局配置
            );
            expect(门派.名称).not.toContain('的');
            expect(门派.名称).not.toBe('拜入门派');
            expect(门派.名称).not.toBe('各门各派');
            expect(武侠词池名.test(门派.名称)).toBe(true);
        }
    });

    it('建档完全没写组织时，保持原有随机生成行为', () => {
        const 门派 = 创建开局门派状态(
            造角色({ 出身背景: { 名称: '寒门孤身', 描述: '自小在山村长大的猎户之子。', 效果: '' } }),
            开局配置
        );

        expect(武侠词池名.test(门派.名称)).toBe(true);
    });

    it('已预填所属门派ID时仍然优先用预填值', () => {
        const 门派 = 创建开局门派状态(
            造角色({
                所属门派ID: '预定门派',
                出身背景: { 名称: '寒门孤身', 描述: '你本是青云剑派的弟子。', 效果: '' }
            }),
            开局配置
        );

        expect(门派.名称).toBe('预定门派');
    });
});
