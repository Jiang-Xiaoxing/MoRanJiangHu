import { describe, expect, it } from 'vitest';
import { 清理角色对话输出 } from '../services/ai/storyTasks';

// 「角色对话」侧聊的正文标签清理：只剥首尾残留，不做全文替换，
// 避免误伤剧情文本里作为字面内容出现的 <正文>。
describe('清理角色对话输出 标签边界清理', () => {
    it('成对标签照常提取', () => {
        expect(清理角色对话输出('<正文>话一</正文>')).toBe('话一');
    });

    it('模型双开标签时剥掉末尾残留的开标签', () => {
        expect(清理角色对话输出('<正文>话二<正文>')).toBe('话二');
    });

    it('孤立闭合标签卡在结尾时剥掉', () => {
        expect(清理角色对话输出('话三</正文>')).toBe('话三');
    });

    it('正文中间的字面 <正文> 不被误删', () => {
        expect(清理角色对话输出('<正文>他展开卷轴，上面写着<正文>四个字</正文>')).toBe(
            '他展开卷轴，上面写着<正文>四个字'
        );
    });

    it('不含标签的普通文本原样保留', () => {
        expect(清理角色对话输出('  今夜月色很好。  ')).toBe('今夜月色很好。');
    });
});
